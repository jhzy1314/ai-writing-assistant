const pipelineStrictSuffix = `优先保证逻辑、事实、框架准确。创作者仅做文字润色，禁止新增原创剧情、论点；校验官提高审查标准，重点核查逻辑漏洞。`

const pipelineArtSuffix = `优先追求文字表现力、故事氛围感。规划师仅提供关键剧情节点，给予创作者充足创作自由度；校验官仅核查严重人设崩坏、重大剧情矛盾，不干涉文学描写、叙事节奏。`

const pipelineLightSuffix = `轻量化文字处理，不启动多轮协作，快速输出结果，不进行二次校验。`

// PipelineSuffix 按流水线名称返回附加提示词
func PipelineSuffix(pipeline string) string {
	switch pipeline {
	case "strict":
		return pipelineStrictSuffix
	case "art":
		return pipelineArtSuffix
	case "light":
		return pipelineLightSuffix
	default:
		return pipelineStandardSuffix
	}
}
